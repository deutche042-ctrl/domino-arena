#!/usr/bin/env node
/*
 * Domino Arena — Android sync step (`node sync.mjs`).
 *
 * Rebuilds mobile/www/ from scratch on every run, then assembles the in-app
 * Node.js project under mobile/www/nodejs/:
 *
 *   www/                     clean copy of ../public  → Capacitor webDir, what
 *                            the WebView loads (assets/public after `cap sync`)
 *   www/nodejs/index.cjs     launcher (copy of ./node/index.cjs)
 *   www/nodejs/package.json  ESM project + "main": "index.cjs"
 *   www/nodejs/server-bundle.cjs
 *                            esbuild CJS bundle of ../server/server.js
 *   www/nodejs/public/       client copy: the bundled server serves the game
 *                            from DOMINO_PUBLIC_DIR
 *
 * Why nodeDir must stay inside webDir: the plugin never reads `webDir`. It looks
 * for its assets at the literal path "public/" + nodeDir (Nodejs.java:154), and
 * Capacitor always publishes webDir as assets/public (CLI dist/config.js). With
 * webDir "www" and nodeDir "nodejs", www/nodejs becomes assets/public/nodejs —
 * the only place the plugin looks.
 */

import { rmSync, mkdirSync, cpSync, existsSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const MOBILE_DIR = path.dirname(fileURLToPath(import.meta.url));
const GAME_DIR = path.resolve(MOBILE_DIR, '..');
const CLIENT_DIR = path.join(GAME_DIR, 'public');          // the game client, no build step
const SERVER_ENTRY = path.join(GAME_DIR, 'server', 'server.js');
const LAUNCHER_SRC = path.join(MOBILE_DIR, 'node', 'index.cjs');

const WWW_DIR = path.join(MOBILE_DIR, 'www');
const NODEJS_DIR = path.join(WWW_DIR, 'nodejs');           // = plugins.Nodejs.nodeDir
const NODEJS_PUBLIC_DIR = path.join(NODEJS_DIR, 'public');
const BUNDLE_OUT = path.join(NODEJS_DIR, 'server-bundle.cjs');

const step = (msg) => console.log('[sync] ' + msg);

function requireDir(dir, label) {
  if (!existsSync(dir) || !statSync(dir).isDirectory()) {
    throw new Error(label + ' not found: ' + dir);
  }
}

function mb(file) {
  return (statSync(file).size / (1024 * 1024)).toFixed(2) + ' MB';
}

async function main() {
  requireDir(CLIENT_DIR, 'game client');
  if (!existsSync(SERVER_ENTRY)) throw new Error('server entry not found: ' + SERVER_ENTRY);
  if (!existsSync(LAUNCHER_SRC)) throw new Error('launcher not found: ' + LAUNCHER_SRC);

  // 1. Clean slate: a stale asset in www/ is an asset that ships in the APK.
  rmSync(WWW_DIR, { recursive: true, force: true });
  mkdirSync(WWW_DIR, { recursive: true });
  step('cleaned ' + WWW_DIR);

  // 2. WebView payload = the current client, byte for byte.
  cpSync(CLIENT_DIR, WWW_DIR, { recursive: true });
  step('copied client → www/ (' + mb(path.join(WWW_DIR, 'index.html')) + ' index.html)');

  // 3. In-app Node.js project.
  mkdirSync(NODEJS_DIR, { recursive: true });
  cpSync(LAUNCHER_SRC, path.join(NODEJS_DIR, 'index.cjs'));
  step('copied launcher → www/nodejs/index.cjs');

  // "type": "module" keeps any plain .js ESM; the two entry points are .cjs so
  // they stay CommonJS regardless. `main` is what the plugin runs when no
  // `script` is passed to start().
  writeFileSync(path.join(NODEJS_DIR, 'package.json'), JSON.stringify({
    name: 'domino-arena-server',
    version: '1.0.0',
    private: true,
    type: 'module',
    main: 'index.cjs',
  }, null, 2) + '\n');
  step('wrote www/nodejs/package.json (main: index.cjs)');

  // 4. One CJS file instead of a node_modules tree: the plugin copies the
  // project out of the APK file-by-file in Java on every app update, so a
  // flatter project means a faster first launch.
  const result = await esbuild.build({
    entryPoints: [SERVER_ENTRY],
    outfile: BUNDLE_OUT,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',                 // plugin runtime is Node 18.20.4
    logLevel: 'warning',
    metafile: true,
    // CommonJS output has no `import.meta`, and esbuild silently replaces it
    // with an empty object — server/server.js:13 does
    // `fileURLToPath(import.meta.url)` at load time, which then throws
    // ERR_INVALID_ARG_TYPE and the server never listens. Point it at the
    // bundle's own file URL so the one use of `here` (the DOMINO_PUBLIC_DIR
    // fallback at server/server.js:91) keeps its upstream meaning.
    define: { 'import.meta.url': '__dominoBundleUrl' },
    banner: {
      js: [
        '/* Domino Arena server bundle — generated by mobile/sync.mjs. Do not edit. */',
        'const __dominoBundleUrl = require("node:url").pathToFileURL(__filename).href;',
      ].join('\n'),
    },
  });
  const inputs = Object.keys(result.metafile.inputs).length;
  step('bundled ' + inputs + ' modules → www/nodejs/server-bundle.cjs (' + mb(BUNDLE_OUT) + ')');

  // 5. The server serves the game itself (server.js: express.static on
  // DOMINO_PUBLIC_DIR) — that copy is what a phone on the LAN opens.
  cpSync(CLIENT_DIR, NODEJS_PUBLIC_DIR, { recursive: true });
  step('copied client → www/nodejs/public/');

  // 6. Fail loudly rather than shipping an APK the plugin will reject with
  // PROJECT_NOT_FOUND / SCRIPT_NOT_FOUND.
  const expected = [
    'index.html',
    'js/app.js',
    'sw.js',
    'nodejs/index.cjs',
    'nodejs/package.json',
    'nodejs/server-bundle.cjs',
    'nodejs/public/index.html',
  ];
  const missing = expected.filter((rel) => !existsSync(path.join(WWW_DIR, rel)));
  if (missing.length) throw new Error('missing after sync: ' + missing.join(', '));
  step('layout check passed (' + expected.length + '/' + expected.length + ')');
  step('done — run `npx cap sync android` to publish www/ into android/app/src/main/assets/public');
}

main().catch((err) => {
  console.error('[sync] FAILED: ' + ((err && err.stack) || err));
  process.exit(1);
});
